"""PDF generation with ReportLab (Platypus). English only: ReportLab cannot shape Devanagari without extra fonts."""
import io
from datetime import datetime
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether

BLUE = colors.HexColor("#0d47a1")
DISCLAIMER = ("This document is generated by an educational software project. It is NOT a medical diagnosis, "
              "prescription or substitute for professional medical advice. Please consult a qualified doctor.")


def _styles():
    s = getSampleStyleSheet()
    s.add(ParagraphStyle("H1x", parent=s["Title"], textColor=BLUE, fontSize=18, spaceAfter=4))
    s.add(ParagraphStyle("H2x", parent=s["Heading2"], textColor=BLUE, fontSize=12, spaceBefore=10, spaceAfter=4))
    s.add(ParagraphStyle("Smallx", parent=s["Normal"], fontSize=8, textColor=colors.grey))
    s.add(ParagraphStyle("Cell", parent=s["Normal"], fontSize=8.5, leading=10.5))
    return s


def build_pdf(title, subtitle, sections, disclaimer=DISCLAIMER):
    """sections: list of {heading, paragraphs:[str], table:{header:[...], rows:[[...]], widths:[mm...]}, notes:[str]}"""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title=title, author="AI Smart Healthcare System")
    st = _styles()
    story = [Paragraph(escape(title), st["H1x"]), Paragraph(escape(subtitle or ""), st["Smallx"]), Spacer(1, 6)]
    for sec in sections:
        block = []
        if sec.get("heading"):
            block.append(Paragraph(escape(sec["heading"]), st["H2x"]))
        for p in sec.get("paragraphs", []):
            block.append(Paragraph(escape(str(p)), st["Normal"]))
            block.append(Spacer(1, 3))
        for n in sec.get("notes", []):
            block.append(Paragraph("&bull; " + escape(str(n)), st["Normal"]))
        t = sec.get("table")
        if t and t.get("rows"):
            data = [[Paragraph(f"<b>{escape(str(h))}</b>", st["Cell"]) for h in t["header"]]]
            data += [[Paragraph(escape("" if c is None else str(c)), st["Cell"]) for c in r] for r in t["rows"]]
            widths = [w * mm for w in t["widths"]] if t.get("widths") else None
            tbl = Table(data, colWidths=widths, repeatRows=1)
            style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e3f2fd")), ("GRID", (0, 0), (-1, -1), 0.4, colors.lightgrey),
                     ("VALIGN", (0, 0), (-1, -1), "TOP"), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f7fbff")])]
            for i, hl in enumerate(t.get("highlight", []), start=1):  # rows to tint red
                if hl:
                    style.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#ffebee")))
            tbl.setStyle(TableStyle(style))
            block.append(tbl)
        story.append(KeepTogether(block) if len(block) < 6 else block[0])
        if len(block) >= 6:
            story.extend(block[1:])
    story += [Spacer(1, 12), Paragraph("<b>Disclaimer:</b> " + escape(disclaimer), st["Smallx"]),
              Paragraph("Generated " + datetime.now().strftime("%d %b %Y, %H:%M"), st["Smallx"])]
    doc.build(story)
    return buf.getvalue()
