"""Generates database/schema.sql (MySQL DDL) straight from the SQLAlchemy models so the two can never drift apart."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateTable, CreateIndex
from models import db  # noqa: E402

lines = ["-- AI Smart Healthcare System: MySQL 8 schema (generated by scripts/export_schema.py)",
         "CREATE DATABASE IF NOT EXISTS smart_healthcare CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;", "USE smart_healthcare;", "SET FOREIGN_KEY_CHECKS = 0;", ""]
for t in db.metadata.sorted_tables:
    lines.append(str(CreateTable(t, if_not_exists=True).compile(dialect=mysql.dialect())).strip().replace("\n\n", "\n") + " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;")
    for ix in sorted(t.indexes, key=lambda i: i.name or ""):
        lines.append(str(CreateIndex(ix).compile(dialect=mysql.dialect())).strip() + ";")
    lines.append("")
lines.append("SET FOREIGN_KEY_CHECKS = 1;")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "database", "schema.sql")
open(path, "w", encoding="utf-8").write("\n".join(lines))
print("wrote", os.path.normpath(path), "-", len(db.metadata.sorted_tables), "tables")
