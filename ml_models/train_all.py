"""Train, evaluate and register all disease models.

    python ml_models\train_all.py            # default: 3000 rows per disease
    python ml_models\train_all.py --n 6000   # more synthetic rows
    python ml_models\train_all.py --only heart

Writes ml_models/saved_models/*.joblib + metrics.json and docs/MODEL_EVALUATION.md, then registers the versions in the DB.
"""
import argparse, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from ml_models import MODULES, common as C  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def write_report(path, model_dir):
    m = C.load_metrics(model_dir)
    lines = ["# Model Evaluation Report", "", "Auto-generated by `ml_models/train_all.py`. Hold-out test split: 25 %, stratified.", "",
             "> **Read this first.** Unless real datasets were supplied in `database/datasets/`, all models are trained on **synthetic** data "
             "whose labels come from a hand-written formula. These numbers prove the pipeline works; they are **not** evidence of clinical accuracy.", ""]
    for d, meta in m.items():
        lines += [f"## {d.title()}", f"- Version: `{meta['version']}`  |  Rows: {meta['n_samples']}  |  Positive rate: {meta['prevalence']}",
                  f"- Data source: {meta['data_source']}", f"- Deployed model (best ROC-AUC): **{meta['best']}**", "",
                  "| Algorithm | Accuracy | Precision | Recall | F1 | ROC-AUC | Confusion matrix [[TN, FP], [FN, TP]] |", "|---|---|---|---|---|---|---|"]
        for a, r in meta["algorithms"].items():
            lines.append(f"| {a} | {r['accuracy']} | {r['precision']} | {r['recall']} | {r['f1']} | {r['roc_auc']} | {r['confusion_matrix']} |")
        lines.append("")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--only", choices=list(MODULES))
    ap.add_argument("--no-db", action="store_true", help="skip registering versions in the database")
    a = ap.parse_args()
    for k, mod in MODULES.items():
        if a.only and k != a.only:
            continue
        print(f"Training {k} ...")
        mod.train(n=a.n, verbose=True)
    write_report(os.path.join(ROOT, "docs", "MODEL_EVALUATION.md"), C.MODEL_DIR)
    print("Saved models + docs/MODEL_EVALUATION.md")
    if not a.no_db:
        from app import create_app
        from utils.model_registry import register_models
        app = create_app()
        with app.app_context():
            register_models()  # (create_app already syncs; this is a no-op safety call)
            from models import ModelVersion
            print(f"model_versions table now holds {ModelVersion.query.count()} rows ({ModelVersion.query.filter_by(is_active=True).count()} active).")


if __name__ == "__main__":
    main()
